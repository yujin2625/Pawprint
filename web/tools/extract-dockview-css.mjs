// dockview-core ships its stylesheet only inside the UMD bundle. This copies it into src/ui/vendor/dockview.css.
// Run after updating dockview-core: node tools/extract-dockview-css.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(web, 'node_modules/dockview-core/package.json'), 'utf8'));
const bundle = readFileSync(join(web, 'node_modules/dockview-core/dist/dockview-core.js'), 'utf8');
const marker = 's.textContent = ';
const start = bundle.indexOf(marker);
if (start < 0) throw new Error('stylesheet not found in the dockview bundle');
// The CSS is one JSON-compatible string literal.
let end = start + marker.length + 1;
while (bundle[end] !== '"' || bundle[end - 1] === '\\') end++;
const css = JSON.parse(bundle.slice(start + marker.length, end + 1));
const out = join(web, 'src/ui/vendor/dockview.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `/* dockview-core ${pkg.version} stylesheet (MIT, https://github.com/mathuo/dockview). Generated by tools/extract-dockview-css.mjs. */\n${css}`);
console.log(`wrote ${out} (${css.length} chars)`);
