const cache = new Map<string, string>();

/** SVG path data for an icon (unit pixels in a 0..10 box). */
export function iconPath(name: string): string {
  let d = cache.get(name);
  if (d === undefined) {
    d = (ROWS[name] ?? []).map((row, y) => [...row].map((ch, x) => (ch === '#' ? `M${x} ${y}h1v1h-1z` : '')).join('')).join('');
    cache.set(name, d);
  }
  return d;
}
